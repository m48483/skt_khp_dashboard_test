"""Generate an idempotent SQL Editor import from the existing workbook snapshot."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def sql_literal(value):
    if value is None:
        return 'NULL'
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"

if __name__ == '__main__':
    raw = (ROOT / 'data/sales.js').read_text(encoding='utf-8')
    data = json.loads(raw.removeprefix('window.SALES_DATA = ').rstrip(';\n'))
    columns = ['id', 'date', 'region', 'store', 'category', 'plan', 'quantity', 'revenue', 'manager']
    values = ["  (" + ', '.join(sql_literal(row[key]) for key in columns) + ")" for row in data['rows']]
    sql = '-- Generated by scripts/prepare_supabase.py. No API keys are required.\nBEGIN;\n\n'
    sql += (ROOT / 'supabase/schema.sql').read_text(encoding='utf-8')
    sql += '\n-- source_row preserves the Excel row number and makes re-running safe.\n'
    sql += 'insert into public.dashboard_sales (source_row, date, region, store, category, plan, quantity, revenue, manager) values\n'
    sql += ',\n'.join(values) + '\non conflict (source_row) do nothing;\n\nCOMMIT;\n\n'
    sql += 'select count(*) as rows, sum(revenue) as revenue, sum(quantity) as quantity,\n'
    sql += '  count(*) filter (where quantity is null) as missing_quantity\nfrom public.dashboard_sales;\n'
    (ROOT / 'supabase/setup.sql').write_text(sql, encoding='utf-8')
    print(f"Prepared {len(values)} rows in supabase/setup.sql")
